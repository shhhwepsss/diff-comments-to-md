'use strict';

/**
 * Generates web/src/styles/dark-slate.css: Primer's dark theme recolored from
 * GitHub's neutral grays to a dark navy slate.
 *
 * Primer's dark.css spells most component tokens (buttons, overlays,
 * controls…) as raw hex instead of referencing the base tokens, so overriding
 * a handful of variables is not enough. Instead every declaration whose value
 * uses one of the neutrals below is re-emitted with the slate equivalent,
 * under the same selectors, and the file is imported after dark.css.
 *
 * Rerun after bumping @primer/primitives:
 *   node tools/local-review/gen-dark-theme.js
 */

const fs = require('node:fs');
const path = require('node:path');

const SRC = require.resolve('@primer/primitives/dist/css/functional/themes/dark.css');
const OUT = path.join(__dirname, 'web/src/styles/dark-slate.css');

// GitHub dark neutral → slate. Alpha suffixes (#656c7633) are kept.
const PALETTE = {
  '010409': '0a0d13',
  '0d1117': '11151d',
  '151b23': '161b25',
  '212830': '1c222e',
  '262c36': '202734',
  '2a313c': '232a38',
  '3d444d': '2a3242',
  '656c76': '535c70',
  '9198a1': '8a93a6',
  'f0f6fc': 'd8dde7',
  // Accent blue → a muted periwinkle.
  '4493f8': '7a9ef0',
  '58a6ff': '7a9ef0',
  '388bfd': '5f80d8',
  '1f6feb': '3f5fb8',
};

// Set outright: syntax colors, the salmon danger text and quieter diff
// backgrounds (GitHub's green and red glare on the dark slate).
const EXTRA = {
  '--fgColor-danger': '#e07a64',
  '--bgColor-success-muted': '#2ea04314',
  '--bgColor-danger-muted': '#f8514912',
  '--diffBlob-additionNum-bgColor': '#2ea04326',
  '--diffBlob-additionWord-bgColor': '#2ea04340',
  '--diffBlob-deletionNum-bgColor': '#f8514926',
  '--diffBlob-deletionWord-bgColor': '#f8514940',
  '--codeMirror-syntax-fgColor-comment': '#5f6880',
  '--codeMirror-syntax-fgColor-constant': '#7a9ef0',
  '--codeMirror-syntax-fgColor-entity': '#b59ae8',
  '--codeMirror-syntax-fgColor-keyword': '#e07a64',
  '--codeMirror-syntax-fgColor-storage': '#e07a64',
  '--codeMirror-syntax-fgColor-string': '#9cc283',
  '--codeMirror-syntax-fgColor-support': '#74b6cc',
  '--codeMirror-syntax-fgColor-variable': '#d4a866',
};

const HEX = new RegExp(`#(${Object.keys(PALETTE).join('|')})(?=[0-9a-f]{2}\\b|\\b)`, 'gi');

/** Selector → recolored declarations, in source order. */
function recolor(css) {
  const blocks = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const selector = m[1].replace(/\/\*[\s\S]*?\*\//g, '').replace(/@media[^{]*\{/, '').trim();
    const decls = [];
    for (const line of m[2].split(';')) {
      const d = line.replace(/\/\*[\s\S]*?\*\//g, '').trim();
      const i = d.indexOf(':');
      if (!d.startsWith('--') || i < 0) continue;
      const name = d.slice(0, i).trim();
      const value = d.slice(i + 1).trim();
      if (EXTRA[name]) decls.push(`${name}: ${EXTRA[name]};`);
      else if (HEX.test(value)) decls.push(`${name}: ${value.replace(HEX, (_, h) => `#${PALETTE[h.toLowerCase()]}`)};`);
      HEX.lastIndex = 0;
    }
    blocks.push({ selector, decls });
  }
  return blocks;
}

const css = fs.readFileSync(SRC, 'utf8');
const media = css.indexOf('@media');
const [main] = recolor(css.slice(0, media));
const [auto] = recolor(css.slice(media));
const indent = (s, n) => s.split('\n').map((l) => ' '.repeat(n) + l).join('\n');

const out = `/* Generated by tools/local-review/gen-dark-theme.js — do not edit by hand. */
${main.selector} {
${indent(main.decls.join('\n'), 2)}
}
@media (prefers-color-scheme: dark) {
  ${auto.selector} {
${indent(auto.decls.join('\n'), 4)}
  }
}
`;

fs.writeFileSync(OUT, out);
console.log(`${path.relative(process.cwd(), OUT)}: ${main.decls.length} tokens`);
